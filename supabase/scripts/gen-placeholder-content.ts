// Writes the placeholder content migration from packages/engine/src/catalog.ts.
// Run with `npm run gen:seed` after changing the catalog. Migrations already
// applied to a project are never rewritten: when content changes, point OUT at
// a new timestamped file so the upserts run again.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  PLACEHOLDER_CARDS,
  PLACEHOLDER_DEFAULT_DECK,
  PLACEHOLDER_ITEM_POOL,
  PLACEHOLDER_ITEMS,
  PLACEHOLDER_POOL,
  PLACEHOLDER_STARTER_LOADOUT,
  SKILLS,
  STARTING_TICKETS,
} from "@gdr/engine";

const OUT = "20261026233000_placeholder_content.sql";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

const sql = `-- GENERATED by supabase/scripts/gen-placeholder-content.ts. Do not edit by hand.
-- PLACEHOLDER content: replace once card design, odds and starting values are decided.

insert into public.skill_definitions (id, name, original, max_level, timing, effect, value, per_level) values
${SKILLS.map(
  (k) =>
    `  (${q(k.id)}, ${q(k.name)}, ${q(k.original)}, ${k.maxLevel}, ${q(k.timing)}, ${q(JSON.stringify(k.effect))}::jsonb, ${k.value}, ${k.perLevel})`,
).join(",\n")}
on conflict (id) do update
  set name = excluded.name, original = excluded.original, max_level = excluded.max_level, timing = excluded.timing,
      effect = excluded.effect, value = excluded.value, per_level = excluded.per_level;

insert into public.card_definitions (id, name, type, attack, draw, rarity, skill_id) values
${PLACEHOLDER_CARDS.map(
  (c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.type)}, ${c.attack}, ${c.draw}, ${q(c.rarity)}, ${c.skill ? q(c.skill) : "null"})`,
).join(",\n")}
on conflict (id) do update
  set name = excluded.name, type = excluded.type, attack = excluded.attack, draw = excluded.draw, rarity = excluded.rarity,
      skill_id = excluded.skill_id;

-- One active pool at a time (card_pools_one_active).
update public.card_pools set active = false where id <> ${q(PLACEHOLDER_POOL.id)};
insert into public.card_pools (id, active) values (${q(PLACEHOLDER_POOL.id)}, true)
on conflict (id) do update set active = true;

insert into public.pool_entries (pool_id, card_id, weight) values
${PLACEHOLDER_POOL.entries.map((e) => `  (${q(PLACEHOLDER_POOL.id)}, ${q(e.id)}, ${e.weight})`).join(",\n")}
on conflict (pool_id, card_id) do update set weight = excluded.weight;

insert into public.item_definitions (id, name, kind, attack, defense) values
${PLACEHOLDER_ITEMS.map((i) => `  (${q(i.id)}, ${q(i.name)}, ${q(i.kind)}, ${i.attack}, ${i.defense})`).join(",\n")}
on conflict (id) do update
  set name = excluded.name, kind = excluded.kind, attack = excluded.attack, defense = excluded.defense;

insert into public.item_pools (id, active) values (${q(PLACEHOLDER_ITEM_POOL.id)}, true)
on conflict (id) do nothing;

insert into public.item_pool_entries (pool_id, item_id, weight) values
${PLACEHOLDER_ITEM_POOL.entries.map((e) => `  (${q(PLACEHOLDER_ITEM_POOL.id)}, ${q(e.id)}, ${e.weight})`).join(",\n")}
on conflict (pool_id, item_id) do update set weight = excluded.weight;

insert into public.game_config (key, value) values
  ('starting_tickets', ${q(JSON.stringify(STARTING_TICKETS))}::jsonb),
  ('default_deck', ${q(JSON.stringify(PLACEHOLDER_DEFAULT_DECK))}::jsonb),
  ('starter_loadout', ${q(JSON.stringify(PLACEHOLDER_STARTER_LOADOUT))}::jsonb)
on conflict (key) do update set value = excluded.value;
`;

const out = fileURLToPath(new URL(`../migrations/${OUT}`, import.meta.url));
writeFileSync(out, sql);
console.log(`wrote ${out}`);
