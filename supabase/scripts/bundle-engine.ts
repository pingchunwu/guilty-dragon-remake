// Bundles packages/engine into the Edge Functions' shared folder, because
// the Supabase deploy only ships files under supabase/functions. Run with
// `npm run gen:engine` after changing the engine; a test checks it is current.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

export const ENGINE_BUNDLE = fileURLToPath(new URL("../functions/_shared/engine.js", import.meta.url));

export async function bundleEngine(): Promise<string> {
  const result = await build({
    entryPoints: [fileURLToPath(new URL("../../packages/engine/src/index.ts", import.meta.url))],
    bundle: true,
    format: "esm",
    target: "es2022",
    write: false,
    legalComments: "none",
    banner: { js: "// GENERATED by supabase/scripts/bundle-engine.ts from packages/engine. Do not edit by hand." },
  });
  // Paths in esbuild's comments differ by checkout; drop them.
  return result.outputFiles[0]!.text.replace(/^\/\/ .*packages\/engine\/src\/.*\n/gm, "");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(ENGINE_BUNDLE, await bundleEngine());
  console.log(`wrote ${ENGINE_BUNDLE}`);
}
